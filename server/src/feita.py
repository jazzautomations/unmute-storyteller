# -*- coding: utf-8 -*-
"""
Feita.ai film pipeline client.

Flow: create session -> send story brief -> poll until the feita agent produces
assets -> assemble a real film locally:
  - video segments generated by feita are concatenated as the core of the film
  - stills become Ken Burns moves opening/closing the video segments
  - title card is drawn with ffmpeg drawtext
The finished mp4 is served via GET /film/{job_id}/file.

Media credits on the account are scarce (~70 usable), so the brief instructs
the feita agent to spend the budget on ONE real video segment (cheapest model,
480P) plus a reference still, and optional extra stills if anything is left.

Runs on plain threads + requests so FastAPI handlers stay sync-simple.
"""
import logging
import os
import shutil
import subprocess
import threading
import time
import uuid
from typing import Any, Dict, List, Optional

import requests

logger = logging.getLogger("uvicorn.error")

FEITA_BASE = "https://api.feita.ai"
POLL_INTERVAL_S = 10
JOB_TIMEOUT_S = 25 * 60
MAX_NUDGES = 4
MIN_READY_ASSETS = 1

FILMS_DIR = os.getenv("FILMS_DIR", "/tmp/storyteller-films")

FILM_BRIEF = """Crie um curta-metragem cinematográfico a partir desta história contada em entrevista de voz.

HISTÓRIA (transcrição da entrevista):
\"\"\"{transcript}\"\"\"


Instruções de produção — SIGA À RISCA:
- O orçamento de mídia da conta é MUITO limitado (~55 créditos). Prioridade
  absoluta: UM segmento de vídeo real de ~10s via modelo TEXT-TO-VIDEO mais
  barato (480P está ótimo — seedance/vidu/etc.), retratando a cena mais forte
  da história. NÃO use modelo que exija still de referência — não cabe no
  orçamento (still 22 + vídeo 50 estoura).
- Se nem um segmento couber, gere até 2 imagens still 16:9 das cenas-chave e
  pare (~44 créditos).
- NÃO faça perguntas e NÃO peça aprovação: escreva um roteiro curto de 3
  batidas e produza imediatamente.
- Diálogo/narração em português brasileiro quando houver fala.
- Estilo cinematográfico e emocional, fiel aos detalhes da história.
"""

APPROVAL_NUDGE = (
    "Aprovado — siga sem perguntas e dentro do orçamento (~55 créditos): "
    "produza o segmento text-to-video de 10s agora. Se crédito faltar, gere "
    "os stills das cenas e pare."
)

CONTINUE_NUDGE = (
    "Pode continuar produzindo o que combinamos — sem perguntas."
)

_JOBS: Dict[str, Dict[str, Any]] = {}
_JOBS_LOCK = threading.Lock()


def _api_key() -> str:
    key = os.getenv("FEITA_API_KEY", "").strip()
    if not key:
        raise RuntimeError("FEITA_API_KEY is not configured")
    return key


def _headers() -> Dict[str, str]:
    return {"Authorization": f"Bearer {_api_key()}"}


def _request(method: str, path: str, timeout: int = 30, **kwargs) -> Any:
    resp = requests.request(
        method, f"{FEITA_BASE}{path}", headers=_headers(), timeout=timeout, **kwargs
    )
    if resp.status_code == 404:
        raise FeitaNotFound(path)
    resp.raise_for_status()
    return resp.json()


class FeitaNotFound(RuntimeError):
    pass


def _find_video_url(payload: Any) -> Optional[str]:
    """Depth-first search for the first http(s) url that looks like a video."""
    if isinstance(payload, dict):
        for key, value in payload.items():
            k = str(key).lower()
            if isinstance(value, str) and value.startswith("http"):
                if any(hint in k for hint in ("video", "export", "render", "film", "url")):
                    if any(ext in value for ext in (".mp4", ".webm", ".mov")) or "video" in k:
                        return value
            found = _find_video_url(value)
            if found:
                return found
    elif isinstance(payload, list):
        for item in payload:
            found = _find_video_url(item)
            if found:
                return found
    return None


def _media_assets(session_id: str) -> List[Dict[str, Any]]:
    """Image/video assets produced in the session, in creation order."""
    try:
        payload = _request("GET", f"/v1/sessions/{session_id}/assets", timeout=30)
    except Exception:
        logger.debug("assets fetch failed", exc_info=True)
        return []
    assets = []
    for asset in payload.get("assets") or []:
        if asset.get("kind") in ("image", "video") and asset.get("url"):
            assets.append(asset)
    assets.sort(key=lambda a: a.get("createdAt") or 0)
    return assets


def _desk_progress(desk_payload: Dict[str, Any]) -> Dict[str, int]:
    desk = desk_payload.get("desk") or {}
    edit = desk_payload.get("edit") or {}
    clips = edit.get("project", {}).get("tracks", [{}])
    n_clips = 0
    for track in clips if isinstance(clips, list) else []:
        n_clips += len(track.get("clips") or [])
    return {
        "docs": len(desk.get("documents") or []),
        "shots": len(desk.get("shots") or []),
        "clips": max(n_clips, len(desk.get("clips") or [])),
        "jobs": len(desk.get("jobs") or []),
    }


def _set(job_id: str, **fields) -> None:
    with _JOBS_LOCK:
        _JOBS[job_id].update(fields)
        _JOBS[job_id]["updated_at"] = time.time()


def start_film(transcript: str, title: Optional[str] = None) -> str:
    _api_key()  # fail fast if unconfigured
    transcript = (transcript or "").strip()
    if not transcript:
        raise ValueError("transcript is required")
    if len(transcript) > 30000:
        transcript = transcript[-30000:]

    job_id = uuid.uuid4().hex[:12]
    with _JOBS_LOCK:
        _JOBS[job_id] = {
            "id": job_id,
            "status": "queued",
            "title": title or "Meu filme",
            "video_url": None,
            "session_id": None,
            "detail": "na fila",
            "created_at": time.time(),
            "updated_at": time.time(),
        }
    thread = threading.Thread(
        target=_run_film, args=(job_id, transcript, title), daemon=True
    )
    thread.start()
    return job_id


def get_job(job_id: str) -> Optional[Dict[str, Any]]:
    with _JOBS_LOCK:
        job = _JOBS.get(job_id)
        return dict(job) if job else None


def film_file(job_id: str) -> Optional[str]:
    job = get_job(job_id)
    if not job:
        return None
    path = job.get("file_path")
    if path and os.path.isfile(path):
        return path
    return None


def _run_film(job_id: str, transcript: str, title: Optional[str]) -> None:
    deadline = time.time() + JOB_TIMEOUT_S
    nudges = 0
    seen_assets = 0
    idle_polls = 0
    try:
        session = _request("POST", "/v1/sessions", json={"name": title or "storyteller"})
        session_id = session["id"]
        _set(job_id, session_id=session_id, status="writing",
             detail="escrevendo o roteiro")

        brief = FILM_BRIEF.format(transcript=transcript)
        _request("POST", f"/v1/sessions/{session_id}/messages",
                 json={"text": brief}, timeout=60)

        while time.time() < deadline:
            time.sleep(POLL_INTERVAL_S)

            session_state = _request("GET", f"/v1/sessions/{session_id}")
            running = bool(session_state.get("running"))

            # A real exported film always wins if the studio produces one.
            try:
                desk_payload = _request("GET", f"/v1/sessions/{session_id}/desk")
            except Exception:
                desk_payload = {}
                logger.debug("desk fetch failed, will retry", exc_info=True)
            exported = _find_video_url(
                {"exported": desk_payload.get("exported"),
                 "media": (desk_payload.get("edit") or {}).get("media")}
            )
            if exported:
                _set(job_id, status="ready", video_url=exported,
                     detail="filme pronto")
                return

            assets = _media_assets(session_id)
            if len(assets) > seen_assets:
                seen_assets = len(assets)
                idle_polls = 0

            if running:
                has_video = any(a["kind"] == "video" for a in assets)
                status = "producing" if (assets or _desk_progress(desk_payload)["jobs"]) else "writing"
                _set(job_id, status=status,
                     detail=("filmando a cena principal" if has_video else
                             "produzindo os materiais" if status == "producing"
                             else "escrevendo o roteiro"),
                     progress={"assets": seen_assets})
                continue

            # agent is idle — with a real video segment we wrap up; with only
            # stills (or nothing) we keep pushing until nudges run out.
            has_video = any(a["kind"] == "video" for a in assets)
            if has_video and nudges >= 1:
                break
            if nudges < MAX_NUDGES:
                nudges += 1
                text = APPROVAL_NUDGE if nudges == 1 else CONTINUE_NUDGE
                _set(job_id, detail="direcionando a produção")
                _nudge(session_id, text)
                continue
            break

        assets = _media_assets(session_id)
        if not assets:
            # Media wallet is empty — the feita agent still wrote the script
            # and scene prompts (text credits). Generate the stills through the
            # free public image API and finish the film locally.
            _set(job_id, status="producing",
                 detail="gerando os frames (crédito de mídia esgotado)")
            prompts = _scene_prompts(session_id, transcript)
            assets = _gen_local_stills(job_id, prompts)

        if not assets:
            _set(job_id, status="error",
                 detail="o estúdio não produziu material a tempo")
            return

        _set(job_id, status="rendering",
             detail="montando o filme final", progress={"assets": len(assets)})
        path = _assemble_film(job_id, assets, title or "Meu filme")
        _set(job_id, status="ready", file_path=path,
             video_url=f"/api/film/{job_id}/file", detail="filme pronto")
    except Exception as exc:
        logger.exception("film job %s failed", job_id)
        _set(job_id, status="error", detail=f"falha: {type(exc).__name__}: {exc}")


def _nudge(session_id: str, text: str) -> None:
    try:
        _request("POST", f"/v1/sessions/{session_id}/messages",
                 json={"text": text}, timeout=60)
    except Exception:
        logger.exception("failed to nudge session %s", session_id)


# --------------------------------------------------------------------------
# Zero-credit fallback: feita wrote the script/prompts as text; render stills
# through the public Pollinations flux endpoint and finish the film locally.
# --------------------------------------------------------------------------

POLLINATIONS_URL = "https://image.pollinations.ai/prompt/{prompt}?width=1344&height=768&model=flux&nologo=true&seed={seed}"
MAX_STILLS = 3


def _scene_prompts(session_id: str, transcript: str) -> List[str]:
    """Pull the scene prompts the feita agent wrote; fall back to transcript chunks."""
    prompts: List[str] = []
    try:
        payload = _request("GET", f"/v1/sessions/{session_id}/messages", timeout=30)
        for msg in reversed(payload.get("messages") or []):
            if msg.get("role") != "assistant":
                continue
            for line in (msg.get("text") or "").splitlines():
                line = line.strip(" -*#\"'")
                lower = line.lower()
                if ("prompt" in lower or "still" in lower) and len(line) > 80:
                    prompts.append(line[:400])
                elif line.startswith(("Cena", "Scene", "Shot", "1.", "2.", "3.")) and len(line) > 100:
                    prompts.append(line[:400])
            if len(prompts) >= MAX_STILLS:
                break
    except Exception:
        logger.debug("could not read session prompts", exc_info=True)

    if not prompts:
        chunks = [c.strip() for c in transcript.split("\n") if len(c.strip()) > 60]
        for chunk in chunks[:MAX_STILLS]:
            prompts.append(f"cinematic film still: {chunk[:300]}")
    return prompts[:MAX_STILLS]


def _gen_local_stills(job_id: str, prompts: List[str]) -> List[Dict[str, Any]]:
    """Generate stills via the free Pollinations endpoint -> fake feita-style assets."""
    from urllib.parse import quote
    work = os.path.join(FILMS_DIR, job_id)
    os.makedirs(work, exist_ok=True)
    assets = []
    for idx, prompt in enumerate(prompts[:MAX_STILLS]):
        styled = (prompt[:350] +
                  ", cinematic film still, dramatic lighting, 16:9 film frame")
        url = POLLINATIONS_URL.format(prompt=quote(styled), seed=1000 + idx)
        dest = os.path.join(work, f"gen_{idx:02d}.png")
        try:
            _download(url, dest)
            if os.path.getsize(dest) < 10000:
                continue
            assets.append({"kind": "image", "local_path": dest,
                           "createdAt": idx})
            logger.info("local still %d generated for job %s", idx, job_id)
        except Exception:
            logger.exception("pollinations still %d failed", idx)
    return assets


# --------------------------------------------------------------------------
# Local assembly: feita video segments + Ken Burns stills -> one mp4
# --------------------------------------------------------------------------

_W, _H, _FPS = 1280, 720, 24
_IMG_SECONDS = 4.5

_FONT_CANDIDATES = [
    "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
]


def _font_path() -> Optional[str]:
    for path in _FONT_CANDIDATES:
        if os.path.isfile(path):
            return path
    return None


def _download(url: str, dest: str) -> None:
    with requests.get(url, stream=True, timeout=120) as resp:
        resp.raise_for_status()
        with open(dest, "wb") as fh:
            shutil.copyfileobj(resp.raw, fh)


def _run_ffmpeg(args: List[str]) -> None:
    proc = subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", *args],
        capture_output=True, text=True, timeout=300,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {proc.stderr[-500:]}")


def _assemble_film(job_id: str, assets: List[Dict[str, Any]], title: str) -> str:
    work = os.path.join(FILMS_DIR, job_id)
    os.makedirs(work, exist_ok=True)
    parts: List[str] = []

    videos = [a for a in assets if a["kind"] == "video"]
    images = [a for a in assets if a["kind"] == "image"]

    # Story order: opening stills -> video segments -> closing stills.
    ordered: List[Dict[str, Any]] = []
    if videos:
        n_open = len(images) // 2
        ordered = images[:n_open] + videos + images[n_open:]
    else:
        ordered = images

    for idx, asset in enumerate(ordered):
        ext = "mp4" if asset["kind"] == "video" else "png"
        local = asset.get("local_path")
        src = local or os.path.join(work, f"src_{idx:02d}.{ext}")
        if not local:
            _download(asset["url"], src)
        part = os.path.join(work, f"part_{idx:02d}.mp4")
        if asset["kind"] == "video":
            _normalize_video(src, part)
        else:
            _ken_burns(src, part, zoom_in=(idx % 2 == 0))
        parts.append(part)

    concat_list = os.path.join(work, "concat.txt")
    with open(concat_list, "w") as fh:
        for part in parts:
            fh.write(f"file '{part}'\n")

    out = os.path.join(FILMS_DIR, f"{job_id}.mp4")
    title_png = _title_card(title, os.path.join(work, "title.png"))
    if title_png:
        _run_ffmpeg([
            "-y", "-f", "concat", "-safe", "0", "-i", concat_list,
            "-i", title_png,
            "-filter_complex",
            "[0:v]fade=t=in:st=0:d=0.6[b];"
            "[b][1:v]overlay=0:0:eof_action=repeat:enable='lt(t,3.4)'[v]",
            "-map", "[v]", "-map", "0:a",
            "-c:v", "libx264", "-preset", "fast", "-crf", "20",
            "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart", out,
        ])
    else:
        _run_ffmpeg([
            "-y", "-f", "concat", "-safe", "0", "-i", concat_list,
            "-vf", "fade=t=in:st=0:d=0.6",
            "-c:v", "libx264", "-preset", "fast", "-crf", "20",
            "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart", out,
        ])
    return out


def _title_card(title: str, out_png: str) -> Optional[str]:
    """Transparent PNG with the film title for the opening overlay."""
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return None
    font_path = _font_path()
    if not font_path:
        return None
    img = Image.new("RGBA", (_W, _H), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    font = ImageFont.truetype(font_path, 58)
    # wrap to ~24 chars per line
    words, lines, line = title.split(), [], ""
    for word in words:
        line = f"{line} {word}".strip()
        if len(line) > 24:
            lines.append(line)
            line = ""
        elif not line:
            lines.append(word)
            line = ""
    if line:
        lines.append(line)
    lines = lines[:3] or [title[:40]]
    text_h = len(lines) * 66
    y = _H - 140 - text_h
    for line in lines:
        bbox = draw.textbbox((0, 0), line, font=font, stroke_width=3)
        x = (_W - (bbox[2] - bbox[0])) / 2
        draw.text((x, y), line, font=font, fill=(255, 255, 255, 255),
                  stroke_width=3, stroke_fill=(0, 0, 0, 220))
        y += 66
    img.save(out_png)
    return out_png


def _ken_burns(src: str, dest: str, zoom_in: bool) -> None:
    frames = int(_IMG_SECONDS * _FPS)
    zoom = "min(zoom+0.0011,1.14)" if zoom_in else "if(eq(on,0),1.14,max(zoom-0.0011,1))"
    _run_ffmpeg([
        "-y", "-i", src,
        "-f", "lavfi", "-t", str(_IMG_SECONDS), "-i", "anullsrc=r=48000:cl=stereo",
        "-filter_complex",
        f"[0:v]scale=2560:1440:force_original_aspect_ratio=increase,"
        f"crop=2560:1440,zoompan=z='{zoom}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)'"
        f":d={frames}:s={_W}x{_H}:fps={_FPS},format=yuv420p[v]",
        "-map", "[v]", "-map", "1:a", "-c:v", "libx264", "-preset", "fast",
        "-crf", "20", "-c:a", "aac", "-shortest", dest,
    ])


def _has_audio(path: str) -> bool:
    proc = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "a",
         "-show_entries", "stream=codec_type", "-of", "csv=p=0", path],
        capture_output=True, text=True, timeout=30,
    )
    return "audio" in proc.stdout


def _normalize_video(src: str, dest: str) -> None:
    video = (
        f"[0:v]scale={_W}:{_H}:force_original_aspect_ratio=decrease,"
        f"pad={_W}:{_H}:(ow-iw)/2:(oh-ih)/2:black,fps={_FPS},format=yuv420p[v]"
    )
    if _has_audio(src):
        args = ["-y", "-i", src, "-filter_complex",
                video + ";[0:a]aresample=48000,aformat=channel_layouts=stereo[a]",
                "-map", "[v]", "-map", "[a]"]
    else:
        args = ["-y", "-i", src, "-f", "lavfi", "-i",
                "anullsrc=r=48000:cl=stereo", "-filter_complex",
                video + ";[1:a]anull[a]", "-map", "[v]", "-map", "[a]", "-shortest"]
    _run_ffmpeg([
        *args, "-c:v", "libx264", "-preset", "fast", "-crf", "20",
        "-c:a", "aac", "-b:a", "128k", dest,
    ])
